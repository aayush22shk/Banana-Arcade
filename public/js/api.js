/**
 * ============================================================================
 * [INTEROPERABILITY & VIRTUAL IDENTITY]: Client-Side REST API Wrapper
 * Architecture: API Client / Service layer
 * Purpose: Handles all asynchronous HTTP requests to backend REST API endpoints,
 *          managing Virtual Identity JWT authorization headers and error handling.
 * ============================================================================
 */

const API_BASE = (() => {
  const path = window.location.pathname;
  const match = path.match(/^(\/[^\/]+)/);
  if (match && match[1].toLowerCase() === '/bananaapi') {
    return `${match[1]}/api`;
  }
  return '/api';
})();

const Api = {
  /**
   * Helper method to manage Virtual Identity JWT storage in browser
   */
  getToken() {
    return localStorage.getItem('banana_arcade_token');
  },

  setToken(token) {
    if (token) {
      localStorage.setItem('banana_arcade_token', token);
    } else {
      localStorage.removeItem('banana_arcade_token');
    }
  },

  clearToken() {
    localStorage.removeItem('banana_arcade_token');
  },

  /**
   * Core HTTP request handler attaching Virtual Identity token when present
   */
  async request(endpoint, options = {}) {
    const url = `${API_BASE}${endpoint}`;
    const headers = {
      'Content-Type': 'application/json',
      ...options.headers
    };

    // [VIRTUAL IDENTITY] Inject Bearer JWT token into request header if authenticated
    const token = this.getToken();
    if (token) {
      headers['Authorization'] = `Bearer ${token}`;
    }

    try {
      const response = await fetch(url, {
        credentials: 'include', // Automatically send and receive Cookies & PHP Sessions
        ...options,
        headers
      });

      const data = await response.json().catch(() => ({}));

      if (!response.ok) {
        throw new Error(data.error || `HTTP error! status: ${response.status}`);
      }

      return data;
    } catch (error) {
      console.error(`[-] API Request Error [${endpoint}]:`, error);
      throw error;
    }
  },

  /**
   * Helper to retrieve a client-readable cookie value
   */
  getCookie(name) {
    const value = `; ${document.cookie}`;
    const parts = value.split(`; ${name}=`);
    if (parts.length === 2) return parts.pop().split(';').shift();
    return null;
  },

  // ==========================================
  // [VIRTUAL IDENTITY] Authentication Services
  // ==========================================
  auth: {
    /**
     * Registers a new virtual player identity with selected avatar
     */
    async register(username, password, avatar = 'avatar-1') {
      const res = await Api.request('/auth/register', {
        method: 'POST',
        body: JSON.stringify({ username, password, avatar })
      });
      if (res.token) Api.setToken(res.token);
      return res;
    },

    /**
     * Authenticates an existing virtual player identity
     */
    async login(username, password) {
      const res = await Api.request('/auth/login', {
        method: 'POST',
        body: JSON.stringify({ username, password })
      });
      if (res.token) Api.setToken(res.token);
      return res;
    },

    /**
     * Updates player avatar in database and session
     */
    async updateAvatar(avatar) {
      const res = await Api.request('/auth/avatar', {
        method: 'POST',
        body: JSON.stringify({ avatar })
      });
      if (res.token) Api.setToken(res.token);
      return res;
    },

    /**
     * Fetches current active virtual identity, avatar and statistics
     */
    async getMe() {
      return await Api.request('/auth/me', {
        method: 'GET'
      });
    },

    /**
     * Terminates the active virtual identity session on both server and client
     */
    async logout() {
      try {
        await Api.request('/auth/logout', {
          method: 'POST'
        });
      } catch (e) {
        console.warn('Logout API call failed, clearing local state:', e);
      } finally {
        Api.clearToken();
      }
    }
  },

  // ==========================================
  // [INTEROPERABILITY] Game & University Banana API
  // ==========================================
  game: {
    /**
     * [INTEROPERABILITY] Fetches a new math puzzle dynamically generated by the University Banana API
     */
    async getPuzzle() {
      return await Api.request('/game/puzzle', {
        method: 'GET'
      });
    },

    /**
     * Verifies solution against server-signed token
     */
    async verifyAnswer(puzzleToken, answer) {
      return await Api.request('/game/verify', {
        method: 'POST',
        body: JSON.stringify({ puzzleToken, answer })
      });
    }
  },

  // ==========================================
  // [VERSION CONTROL] Leaderboard & Persistence
  // ==========================================
  leaderboard: {
    /**
     * Retrieves global top 10 high scores with optional difficulty filter
     */
    async getTop(difficulty = null) {
      const qs = difficulty && difficulty !== 'all' ? `?difficulty=${encodeURIComponent(difficulty)}` : '';
      return await Api.request(`/leaderboard${qs}`, {
        method: 'GET'
      });
    },

    /**
     * [VIRTUAL IDENTITY] Submits high score to persistent MySQL database with difficulty mode
     */
    async submit(score, puzzlesSolved, difficulty = 'medium') {
      return await Api.request('/leaderboard/submit', {
        method: 'POST',
        body: JSON.stringify({ score, puzzlesSolved, difficulty })
      });
    }
  },

  // ==========================================
  // [EVENT-DRIVEN MULTIPLAYER] 1v1 Versus Arena
  // ==========================================
  multiplayer: {
    /**
     * Creates a new 1v1 battle room and returns unique code
     */
    async create(username, avatar) {
      return await Api.request('/multiplayer/create', {
        method: 'POST',
        body: JSON.stringify({ username, avatar })
      });
    },

    /**
     * Joins an existing room by room code
     */
    async join(roomCode, username, avatar) {
      return await Api.request('/multiplayer/join', {
        method: 'POST',
        body: JSON.stringify({ roomCode, username, avatar })
      });
    },

    /**
     * Polls the current room status
     */
    async getStatus(roomCode) {
      return await Api.request(`/multiplayer/status?roomCode=${encodeURIComponent(roomCode)}`, {
        method: 'GET'
      });
    },

    /**
     * Sends action (submit_answer, rematch, leave)
     */
    async sendAction(roomCode, role, action, data = {}) {
      return await Api.request('/multiplayer/action', {
        method: 'POST',
        body: JSON.stringify({ roomCode, role, action, ...data })
      });
    }
  },

  // ==========================================
  // [TROPHIES & ACHIEVEMENTS]
  // ==========================================
  achievements: {
    /**
     * Fetches the 18 trophies, unlock statuses, and player stats
     */
    async get(playerId = null) {
      const qs = playerId ? `?playerId=${encodeURIComponent(playerId)}` : '';
      return await Api.request(`/achievements${qs}`, {
        method: 'GET'
      });
    },

    /**
     * Records a game event (solo_game_completed, multiplayer_match_ended, combo_reached)
     */
    async recordEvent(event, data = {}, playerId = null) {
      return await Api.request('/achievements/event', {
        method: 'POST',
        body: JSON.stringify({ event, data, playerId })
      });
    }
  }
};

window.Api = Api;
