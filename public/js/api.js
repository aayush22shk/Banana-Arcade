/**
 * ============================================================================
 * [INTEROPERABILITY & VIRTUAL IDENTITY]: Client-Side REST API Wrapper
 * Architecture: API Client / Service layer
 * Purpose: Handles all asynchronous HTTP requests to backend REST API endpoints,
 *          managing Virtual Identity JWT authorization headers and error handling.
 * ============================================================================
 */

const API_BASE = (() => {
  const path = window.location.pathname;
  const match = path.match(/^(\/[^\/]+)/);
  if (match && match[1].toLowerCase() === '/bananaapi') {
    return `${match[1]}/api`;
  }
  return '/api';
})();

const Api = {
  /**
   * Helper method to manage Virtual Identity JWT storage in browser
   */
  getToken() {
    return localStorage.getItem('banana_arcade_token');
  },

  setToken(token) {
    if (token) {
      localStorage.setItem('banana_arcade_token', token);
    } else {
      localStorage.removeItem('banana_arcade_token');
    }
  },

  clearToken() {
    localStorage.removeItem('banana_arcade_token');
  },

  /**
   * Core HTTP request handler attaching Virtual Identity token when present
   */
  async request(endpoint, options = {}) {
    const url = `${API_BASE}${endpoint}`;
    const headers = {
      'Content-Type': 'application/json',
      ...options.headers
    };

    // [VIRTUAL IDENTITY] Inject Bearer JWT token into request header if authenticated
    const token = this.getToken();
    if (token) {
      headers['Authorization'] = `Bearer ${token}`;
    }

    try {
      const response = await fetch(url, {
        ...options,
        headers
      });

      const data = await response.json().catch(() => ({}));

      if (!response.ok) {
        throw new Error(data.error || `HTTP error! status: ${response.status}`);
      }

      return data;
    } catch (error) {
      console.error(`[-] API Request Error [${endpoint}]:`, error);
      throw error;
    }
  },

  // ==========================================
  // [VIRTUAL IDENTITY] Authentication Services
  // ==========================================
  auth: {
    /**
     * Registers a new virtual player identity
     */
    async register(username, password) {
      const res = await Api.request('/auth/register', {
        method: 'POST',
        body: JSON.stringify({ username, password })
      });
      if (res.token) Api.setToken(res.token);
      return res;
    },

    /**
     * Authenticates an existing virtual player identity
     */
    async login(username, password) {
      const res = await Api.request('/auth/login', {
        method: 'POST',
        body: JSON.stringify({ username, password })
      });
      if (res.token) Api.setToken(res.token);
      return res;
    },

    /**
     * Fetches current active virtual identity and statistics
     */
    async getMe() {
      return await Api.request('/auth/me', {
        method: 'GET'
      });
    },

    /**
     * Terminates the active virtual identity session
     */
    logout() {
      Api.clearToken();
    }
  },

  // ==========================================
  // [INTEROPERABILITY] Game & University Banana API
  // ==========================================
  game: {
    /**
     * [INTEROPERABILITY] Fetches a new math puzzle dynamically generated by the University Banana API
     */
    async getPuzzle() {
      return await Api.request('/game/puzzle', {
        method: 'GET'
      });
    },

    /**
     * Verifies solution against server-signed token
     */
    async verifyAnswer(puzzleToken, answer) {
      return await Api.request('/game/verify', {
        method: 'POST',
        body: JSON.stringify({ puzzleToken, answer })
      });
    }
  },

  // ==========================================
  // [VERSION CONTROL] Leaderboard & Persistence
  // ==========================================
  leaderboard: {
    /**
     * Retrieves global top 10 high scores
     */
    async getTop() {
      return await Api.request('/leaderboard', {
        method: 'GET'
      });
    },

    /**
     * [VIRTUAL IDENTITY] Submits high score to persistent SQLite database
     */
    async submit(score, puzzlesSolved) {
      return await Api.request('/leaderboard/submit', {
        method: 'POST',
        body: JSON.stringify({ score, puzzlesSolved })
      });
    }
  }
};

window.Api = Api;
